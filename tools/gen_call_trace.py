# Generates src/call_trace_hooks.inc: a REX_HOOK_RAW wrapper per traced function that
# records the call's registers (when recomp_call_trace is on) and runs the original.
# Usage: python tools/gen_call_trace.py tools/call_trace_funcs.txt src/call_trace_hooks.inc
import sys
addrs = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
out = ['// Generated by tools/gen_call_trace.py - do not edit.', '']
for i, a in enumerate(addrs):
    out.append(f'extern "C" void __imp__sub_{a}(PPCContext& __restrict ctx, uint8_t* base);')
    out.append(f'REX_HOOK_RAW(sub_{a}) {{ call_trace::record({i}, 0x{a}u, ctx); __imp__sub_{a}(ctx, base); }}')
out += ['', f'static constexpr uint32_t kTracedCount = {len(addrs)};', '']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
